#!/usr/bin/env node
// Generates every AI tool's project config (Claude Code, Codex, OpenCode)
// from the canonical sources:
//   .agent-docs/agent-config.json  MCP servers + actions that require approval
//   .claude/agents/*.md            subagents
//   .claude/skills/*/SKILL.md      skills
// Usage: node scripts/sync-agent-config.mjs [--check]

import { execFileSync } from "node:child_process";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const problems = [];

const config = JSON.parse(readFileSync(join(root, ".agent-docs/agent-config.json"), "utf8"));
const servers = Object.entries(config.mcpServers);
const gatedServers = servers.filter(([, server]) => server.requireApproval).map(([name]) => name);
const gatedCommands = config.shellCommandsRequiringApproval;

const GENERATED = "Generated by scripts/sync-agent-config.mjs from .agent-docs/agent-config.json. Do not edit.";

function formatJson(path, value) {
  return execFileSync(join(root, "node_modules/.bin/biome"), ["format", `--stdin-file-path=${path}`], {
    cwd: root,
    input: `${JSON.stringify(value, null, 2)}\n`,
    encoding: "utf8",
  });
}

function emit(path, content) {
  const absolute = join(root, path);
  const current = existsSync(absolute) ? readFileSync(absolute, "utf8") : null;
  if (current === content) return;
  if (check) {
    problems.push(`${path} is out of date`);
    return;
  }
  mkdirSync(dirname(absolute), { recursive: true });
  writeFileSync(absolute, content);
  console.log(`wrote ${path}`);
}

function emitSymlinks(dir, targets) {
  const absoluteDir = join(root, dir);
  const existing = existsSync(absoluteDir) ? readdirSync(absoluteDir) : [];

  for (const entry of existing) {
    if (entry in targets) continue;
    if (check) problems.push(`${dir}/${entry} is stale`);
    else {
      rmSync(join(absoluteDir, entry), { recursive: true, force: true });
      console.log(`removed ${dir}/${entry}`);
    }
  }

  for (const [entry, target] of Object.entries(targets)) {
    const link = join(absoluteDir, entry);
    const expected = relative(absoluteDir, join(root, target));
    const isCorrect = existsSync(link) && lstatSync(link).isSymbolicLink() && readlinkSync(link) === expected;
    if (isCorrect) continue;
    if (check) {
      problems.push(`${dir}/${entry} must be a symlink to ${expected}`);
      continue;
    }
    mkdirSync(absoluteDir, { recursive: true });
    rmSync(link, { recursive: true, force: true });
    symlinkSync(expected, link);
    console.log(`linked ${dir}/${entry} -> ${expected}`);
  }
}

function parseAgent(file) {
  const source = readFileSync(join(root, ".claude/agents", file), "utf8");
  const match = source.match(/^---\n([\s\S]*?)\n---\n+([\s\S]*)$/);
  if (!match) throw new Error(`.claude/agents/${file}: missing frontmatter`);
  const frontmatter = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const separator = line.indexOf(":");
      return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
    }),
  );
  if (frontmatter.name !== file.replace(/\.md$/, "")) throw new Error(`.claude/agents/${file}: name must match file`);
  if (!frontmatter.description) throw new Error(`.claude/agents/${file}: description is required`);
  return { name: frontmatter.name, description: frontmatter.description, body: match[2].trimEnd() };
}

const tomlString = (value) => JSON.stringify(value);
const tomlArray = (values) => `[${values.map(tomlString).join(", ")}]`;
const tomlKey = (key) => (/^[A-Za-z0-9_-]+$/.test(key) ? key : tomlString(key));

// MCP: Claude Code
emit(
  ".mcp.json",
  formatJson(".mcp.json", {
    mcpServers: Object.fromEntries(
      servers.map(([name, server]) => [
        name,
        server.url
          ? {
              type: "http",
              url: server.url,
              ...(server.bearerTokenEnv && { headers: { Authorization: `Bearer \${${server.bearerTokenEnv}}` } }),
            }
          : {
              command: server.command,
              args: server.args,
              env: {
                ...Object.fromEntries((server.envFromShell ?? []).map((name) => [name, `\${${name}}`])),
                ...server.env,
              },
            },
      ]),
    ),
  }),
);

// MCP + MCP approval: Codex
const codexServers = servers.map(([name, server]) => {
  const lines = [`[mcp_servers.${tomlKey(name)}]`];
  if (server.url) {
    lines.push(`url = ${tomlString(server.url)}`);
    if (server.bearerTokenEnv) lines.push(`bearer_token_env_var = ${tomlString(server.bearerTokenEnv)}`);
  } else {
    lines.push(`command = ${tomlString(server.command)}`, `args = ${tomlArray(server.args)}`);
    if (server.envFromShell) lines.push(`env_vars = ${tomlArray(server.envFromShell)}`);
  }
  if (server.requireApproval) lines.push(`default_tools_approval_mode = "prompt"`);
  if (server.env) {
    lines.push("", `[mcp_servers.${tomlKey(name)}.env]`);
    for (const [key, value] of Object.entries(server.env)) lines.push(`${key} = ${tomlString(value)}`);
  }
  return lines.join("\n");
});
emit(
  ".codex/config.toml",
  `# ${GENERATED}\n# Codex loads this project layer only after you trust the project.\n\n${codexServers.join("\n\n")}\n`,
);

// Shell approval: Codex
emit(
  ".codex/rules/project.rules",
  `# ${GENERATED}\n\n${gatedCommands
    .map(
      (pattern) =>
        `prefix_rule(\n    pattern = ${tomlArray(pattern)},\n    decision = "prompt",\n    justification = "Requires explicit user approval (AGENTS.md hard rules)",\n)`,
    )
    .join("\n\n")}\n`,
);

// Shell + MCP approval: Claude Code
emit(
  ".claude/settings.json",
  formatJson(".claude/settings.json", {
    $schema: "https://json.schemastore.org/claude-code-settings.json",
    permissions: {
      ask: [
        ...gatedCommands.map((pattern) => `Bash(${pattern.join(" ")} *)`),
        ...gatedServers.map((name) => `mcp__${name}`),
      ],
    },
  }),
);

// MCP + approval: OpenCode
emit(
  "opencode.json",
  formatJson("opencode.json", {
    $schema: "https://opencode.ai/config.json",
    permissions: [
      ...gatedCommands.map((pattern) => ({ action: "shell", resource: `${pattern.join(" ")} *`, effect: "ask" })),
      ...gatedServers.map((name) => ({
        action: `${name.replace(/[^A-Za-z0-9_]/g, "?")}_*`,
        resource: "*",
        effect: "ask",
      })),
    ],
    mcp: {
      servers: Object.fromEntries(
        servers.map(([name, server]) => [
          name,
          server.url
            ? {
                type: "remote",
                url: server.url,
                oauth: false,
                ...(server.bearerTokenEnv && { headers: { Authorization: `Bearer {env:${server.bearerTokenEnv}}` } }),
              }
            : {
                type: "local",
                command: [server.command, ...server.args],
                environment: {
                  ...Object.fromEntries((server.envFromShell ?? []).map((name) => [name, `{env:${name}}`])),
                  ...server.env,
                },
              },
        ]),
      ),
    },
  }),
);

// Subagents
const agents = readdirSync(join(root, ".claude/agents"))
  .filter((file) => file.endsWith(".md"))
  .map(parseAgent);

for (const agent of agents) {
  if (agent.body.includes("'''")) throw new Error(`.claude/agents/${agent.name}.md: body must not contain '''`);
  emit(
    `.codex/agents/${agent.name}.toml`,
    `# Generated by scripts/sync-agent-config.mjs from .claude/agents/${agent.name}.md. Do not edit.\nname = ${tomlString(agent.name)}\ndescription = ${tomlString(agent.description)}\ndeveloper_instructions = '''\n${agent.body}\n'''\n`,
  );
}
const codexAgentsDir = join(root, ".codex/agents");
for (const file of existsSync(codexAgentsDir) ? readdirSync(codexAgentsDir) : []) {
  if (agents.some((agent) => `${agent.name}.toml` === file)) continue;
  if (check) problems.push(`.codex/agents/${file} is stale`);
  else rmSync(join(codexAgentsDir, file));
}

const agentLinks = Object.fromEntries(agents.map(({ name }) => [`${name}.md`, `.claude/agents/${name}.md`]));
emitSymlinks(".opencode/agents", agentLinks);

// Skills (Claude Code and OpenCode read .claude/skills; Codex needs .agents/skills)
const skills = readdirSync(join(root, ".claude/skills")).filter((entry) =>
  existsSync(join(root, ".claude/skills", entry, "SKILL.md")),
);
emitSymlinks(".agents/skills", Object.fromEntries(skills.map((name) => [name, `.claude/skills/${name}`])));

if (problems.length > 0) {
  console.error(`AI tool config is out of sync. Run \`pnpm agents:sync\`.\n- ${problems.join("\n- ")}`);
  process.exit(1);
}
if (check) console.log("AI tool config is in sync.");
